CREATE TABLE soop_subscription (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  soop_user_id VARCHAR2(255) NOT NULL,
  soop_channel_name VARCHAR2(255) NOT NULL,
  profile_image_url VARCHAR2(30000),
  is_live NUMBER(1) DEFAULT 0 NOT NULL,
  live_title VARCHAR2(500),
  broad_no VARCHAR2(255),
  live_url VARCHAR2(30000),
  enabled NUMBER(1) DEFAULT 1 NOT NULL,
  notify_online NUMBER(1) DEFAULT 1 NOT NULL,
  notify_offline NUMBER(1) DEFAULT 1 NOT NULL,
  content VARCHAR2(2000),
  color_hex VARCHAR2(11) DEFAULT '9146FF' NOT NULL,
  webhook_id NUMBER NOT NULL,
  bot_profile_id NUMBER NOT NULL,
  form_owner VARCHAR2(255) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  last_check_time TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT fk_soop_subscription_webhook_id FOREIGN KEY (webhook_id) REFERENCES discord_webhook_data(id),
  CONSTRAINT fk_soop_subscription_bot_profile_id FOREIGN KEY (bot_profile_id) REFERENCES discord_bot_profile_data(id),
  CONSTRAINT fk_soop_subscription_owner_channel_id FOREIGN KEY (form_owner) REFERENCES chzzk_channel(channel_id)
);
