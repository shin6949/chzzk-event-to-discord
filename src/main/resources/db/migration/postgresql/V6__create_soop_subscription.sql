CREATE TABLE IF NOT EXISTS soop_subscription (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  soop_user_id VARCHAR(255) NOT NULL,
  soop_channel_name VARCHAR(255) NOT NULL,
  profile_image_url VARCHAR(30000),
  is_live BOOLEAN NOT NULL DEFAULT false,
  live_title VARCHAR(500),
  broad_no VARCHAR(255),
  live_url VARCHAR(30000),
  enabled BOOLEAN NOT NULL DEFAULT true,
  notify_online BOOLEAN NOT NULL DEFAULT true,
  notify_offline BOOLEAN NOT NULL DEFAULT true,
  content VARCHAR(2000),
  color_hex VARCHAR(11) NOT NULL DEFAULT '9146FF',
  webhook_id BIGINT NOT NULL,
  bot_profile_id BIGINT NOT NULL,
  form_owner VARCHAR(255) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_check_time TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_soop_subscription_webhook_id FOREIGN KEY (webhook_id) REFERENCES discord_webhook_data(id),
  CONSTRAINT fk_soop_subscription_bot_profile_id FOREIGN KEY (bot_profile_id) REFERENCES discord_bot_profile_data(id),
  CONSTRAINT fk_soop_subscription_owner_channel_id FOREIGN KEY (form_owner) REFERENCES chzzk_channel(channel_id)
);
